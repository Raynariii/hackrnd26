package io.blueprints.analysis.llm;

import java.util.Optional;

/**
 * Советчик по оптимизации кода. Детерминированные исправления живут в {@code fixes/}; этот интерфейс —
 * для случаев, где правило не справляется (D6: сначала правила, LLM — дополнение).
 *
 * <p>Советчик только предлагает текст. Применение — отдельный шаг с quality gate (компиляция +
 * дифф-тесты), поэтому LLM не может незаметно сломать поведение программы. Без ключа в окружении
 * реализация выключена ({@link #enabled()} = {@code false}) и молча возвращает пустой ответ.
 */
public interface OptimizationAdvisor {

    /** Включён ли советчик (есть ли ключ). Выключенный не делает сетевых вызовов. */
    boolean enabled();

    /** Совет по находке; {@link Optional#empty()} — советчик выключен, ошибка сети или пустой ответ. */
    Optional<Advice> advise(AdviceRequest request);
}
